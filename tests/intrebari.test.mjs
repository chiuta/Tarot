// Jurnal de întrebări și simbolism (v2.0.0). Rulare: node tests/intrebari.test.mjs
import {createRequire} from 'module'; import path from 'node:path'; import {fileURLToPath} from 'node:url'; import fs from 'node:fs';
const require = createRequire(process.env.PW_ROOT || import.meta.url); const {chromium} = require('playwright');
const HERE = path.dirname(fileURLToPath(import.meta.url)); const FILE = 'file://' + path.join(HERE, '..', 'index.html');
let ok = 0, bad = 0; const t = (n, c, x) => { if (c) { ok++; console.log('  ok  ', n); } else { bad++; console.log('  FAIL', n, x ?? ''); } };
const b = await chromium.launch({executablePath: process.env.CHROMIUM_PATH || undefined, args: ['--no-sandbox']});
const ctx = await b.newContext({viewport: {width: 1100, height: 900}, locale: 'en-US', acceptDownloads: true});
const net = []; await ctx.route(/^https?:/, r => { net.push(r.request().url()); r.abort(); });
const p = await ctx.newPage(); const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
await p.goto(FILE); await p.waitForTimeout(400); await p.selectOption('#langSel', 'en');
await p.click('a[data-target="intrebari"]');
t('panou vizibil', await p.isVisible('#intrebari'));
t('biblioteca are 22 de arcane', (await p.$$('#qiLib details')).length === 22);
t('avertisment: reflecție, nu predicție', /not for prediction/.test(await p.textContent('#intrebari')));
await p.click('#qiDrawBtn');
t('o carte extrasă cu simbolism', (await p.$$('#qiResult .qi-card')).length === 1 && (await p.textContent('#qiResult .qi-sym')).length > 40);
await p.selectOption('#qiSpread', '3'); await p.click('#qiDrawBtn');
const names = await p.$$eval('#qiResult .qi-cname', e => e.map(x => x.textContent));
t('trei cărți distincte, cu poziții', names.length === 3 && new Set(names).size === 3 && /^Situation:/.test(names[0]), names);
await p.fill('#qiQuestion', 'What do I want to understand about this month?'); await p.fill('#qiNote', 'Calm <b>note</b>');
await p.click('#qiSaveBtn');
t('o înregistrare în istoric', (await p.$$('#qiList li')).length === 1 && /1 entries/.test(await p.textContent('#qiCount')));
t('nota și întrebarea afișate ca text (fără HTML)', (await p.textContent('#qiList li')).includes('<b>note</b>') && (await p.$$('#qiList b')).length === 0);
t('persistat în localStorage (tarot.istoric)', await p.evaluate(() => JSON.parse(localStorage.getItem('tarot.istoric'))[0].c.length === 3));
await p.reload(); await p.waitForTimeout(300); await p.click('a[data-target="intrebari"]');
t('istoricul supraviețuiește reîncărcării', (await p.$$('#qiList li')).length === 1);
await p.fill('#qiFilter', 'zzzz'); t('filtru fără rezultate', (await p.$$('#qiList li')).length === 0);
await p.fill('#qiFilter', 'month'); t('filtru cu rezultat', (await p.$$('#qiList li')).length === 1);
const [dl] = await Promise.all([p.waitForEvent('download'), p.click('#qiExpJson')]);
const js = JSON.parse(fs.readFileSync(await dl.path(), 'utf8')); t('export JSON valid', js.format === 'tarot-istoric' && js.entries.length === 1);
await p.click('#qiList .qi-del'); await p.waitForSelector('dialog[open]');
await p.click('dialog[open] .fff-primary'); await p.waitForTimeout(200);
t('ștergere cu dialog propriu', (await p.$$('#qiList li')).length === 0);
await p.selectOption('#langSel', 'ro'); t('RO: titlu', /Jurnal de întrebări/.test(await p.textContent('#intrebari h2')));
t('RO: simbolism în română', /călător|Nebun/i.test(await p.textContent('#qiLib')));
t('fără erori/CSP', errs.length === 0, errs); t('0 cereri de rețea', net.length === 0, net);
await b.close(); console.log(`\n${ok} reușite, ${bad} eșuate`); process.exit(bad ? 1 : 0);
